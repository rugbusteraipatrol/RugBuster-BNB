/**
 * Regenerates server/test/fixtures/MockUSDC.json from MockUSDC.sol.
 *
 * The compiled artifact is checked in so the test suite needs no Solidity
 * toolchain (and so BasePay carries no compiler dependency for a test fixture).
 * Run this only when the contract changes:
 *
 *   npm i --no-save solc@0.8.28 && node scripts/compile-mock-usdc.mjs
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const solc = require('solc');

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(here, '../server/test/fixtures/MockUSDC.sol');
const outputPath = path.resolve(here, '../server/test/fixtures/MockUSDC.json');

const input = {
  language: 'Solidity',
  sources: { 'MockUSDC.sol': { content: readFileSync(sourcePath, 'utf8') } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length > 0) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}

const contract = output.contracts['MockUSDC.sol'].MockUSDC;
writeFileSync(
  outputPath,
  `${JSON.stringify(
    {
      _comment: 'Generated by scripts/compile-mock-usdc.mjs. Do not edit by hand.',
      compiler: solc.version(),
      settings: { optimizer: input.settings.optimizer },
      abi: contract.abi,
      bytecode: `0x${contract.evm.bytecode.object}`,
    },
    null,
    2,
  )}\n`,
);

console.log(`wrote ${outputPath} (${contract.evm.bytecode.object.length / 2} bytes of bytecode)`);
