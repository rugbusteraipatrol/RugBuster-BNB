import { randomBytes } from 'node:crypto';
import { Router, type Request } from 'express';
import type pg from 'pg';
import { z } from 'zod';
import { normalizeAddress } from '../../address.js';
import type { Config } from '../../config.js';
import { getMerchant, registerMerchant, updateMerchant } from '../../db/merchants.js';
import { isUniqueViolation } from '../../db/pool.js';
import { countBillableSessions } from '../../db/sessions.js';
import type { Merchant } from '../../db/types.js';
import { badRequest, notFound, unauthorized } from '../../errors.js';
import { logger } from '../../logger.js';
import { effectivePlan, merchantIdFor, monthStart } from '../../merchants/plans.js';
import { assertPublicWebhookUrl, verifyWebhookEndpoint, type FetchLike } from '../../merchants/verifyWebhook.js';
import { randomToken, safeEqual, sha256Hex } from '../../secrets.js';
import { asyncRoute, rateLimitByIp } from '../middleware.js';

const webhookSecretSchema = z.string().min(32).max(256);

const registerSchema = z.object({
  walletAddress: z.string(),
  webhookUrl: z.string().max(2048),
  /** Generated by the registrant: it is the receiver's secret, and the challenge proves they hold it. */
  webhookSecret: webhookSecretSchema,
  siteUrl: z.string().url().max(2048).optional(),
  platform: z.string().min(1).max(64).regex(/^[a-z0-9._-]+$/i).optional(),
});

const updateSchema = z
  .object({
    walletAddress: z.string().optional(),
    webhookUrl: z.string().max(2048).optional(),
    webhookSecret: webhookSecretSchema.optional(),
  })
  .refine((v) => (v.webhookUrl === undefined) === (v.webhookSecret === undefined), {
    message: 'webhookUrl and webhookSecret must be provided together',
  })
  .refine((v) => v.walletAddress !== undefined || v.webhookUrl !== undefined, { message: 'nothing to update' });

export interface MerchantRoutesOptions {
  /** Injected by tests so the challenge can hit an in-process receiver. */
  fetchImpl?: FetchLike;
}

/**
 * Self-service merchant API. This is what makes "paste your wallet address and
 * you are live" possible: no operator, no account, no dashboard. A registrant
 * proves it controls its webhook endpoint before a row is written, and gets
 * back a merchant key that authorises later changes and the usage view.
 */
export function merchantRoutes(config: Config, pool: pg.Pool, options: MerchantRoutesOptions = {}): Router {
  const router = Router();
  const production = config.nodeEnv === 'production';
  const fetchImpl = options.fetchImpl;

  router.post(
    '/merchants',
    rateLimitByIp(
      config.merchants.registrationRateLimitPerHour,
      3_600_000,
      'RATE_LIMITED',
      'Too many registrations from this address. Try again in an hour.',
    ),
    asyncRoute(async (req, res) => {
      if (!config.merchants.registrationEnabled) {
        throw notFound('REGISTRATION_DISABLED', 'Self-registration is not enabled on this service');
      }
      const parsed = registerSchema.safeParse(req.body);
      if (!parsed.success) throw invalid(parsed.error);
      const input = parsed.data;

      const walletAddress = normalizeAddress(input.walletAddress, 'walletAddress');
      const webhookUrl = assertPublicWebhookUrl(input.webhookUrl, production).toString();
      await verifyWebhookEndpoint(webhookUrl, input.webhookSecret, fetchImpl);

      const merchantKey = randomToken('bpk_');
      let merchant: Merchant | null = null;
      for (let attempt = 0; attempt < 5 && !merchant; attempt += 1) {
        const id = merchantIdFor(input.siteUrl ?? null, randomBytes(4).toString('hex'));
        try {
          merchant = await registerMerchant(pool, {
            id,
            walletAddress,
            webhookUrl,
            webhookSecret: input.webhookSecret,
            merchantKeyHash: sha256Hex(merchantKey),
            siteUrl: input.siteUrl ?? null,
            platform: input.platform ?? null,
          });
        } catch (err) {
          if (!isUniqueViolation(err, 'merchants_pkey')) throw err;
        }
      }
      if (!merchant) throw new Error('could not allocate a merchant id');

      logger.info({ merchantId: merchant.id, platform: merchant.platform, siteUrl: merchant.siteUrl }, 'merchant registered');
      res.status(201).json({
        merchantId: merchant.id,
        // Shown once. Only its hash is stored.
        merchantKey,
        walletAddress: merchant.walletAddress,
        ...(await planView(merchant)),
      });
    }),
  );

  router.get(
    '/merchants/:id',
    asyncRoute(async (req, res) => {
      const merchant = await authenticate(req);
      res.setHeader('cache-control', 'no-store');
      res.json({
        merchantId: merchant.id,
        walletAddress: merchant.walletAddress,
        webhookUrl: merchant.webhookUrl,
        siteUrl: merchant.siteUrl,
        ...(await planView(merchant)),
      });
    }),
  );

  router.patch(
    '/merchants/:id',
    asyncRoute(async (req, res) => {
      const merchant = await authenticate(req);
      const parsed = updateSchema.safeParse(req.body);
      if (!parsed.success) throw invalid(parsed.error);
      const input = parsed.data;

      const update: Parameters<typeof updateMerchant>[2] = {};
      if (input.walletAddress !== undefined) {
        update.walletAddress = normalizeAddress(input.walletAddress, 'walletAddress');
      }
      if (input.webhookUrl !== undefined && input.webhookSecret !== undefined) {
        const url = assertPublicWebhookUrl(input.webhookUrl, production).toString();
        await verifyWebhookEndpoint(url, input.webhookSecret, fetchImpl);
        update.webhook = { url, secret: input.webhookSecret };
      }

      const updated = await updateMerchant(pool, merchant.id, update);
      if (!updated) throw notFound('MERCHANT_NOT_FOUND', 'No such merchant');
      logger.info({ merchantId: updated.id, fields: Object.keys(update) }, 'merchant updated');
      res.json({
        merchantId: updated.id,
        walletAddress: updated.walletAddress,
        webhookUrl: updated.webhookUrl,
        ...(await planView(updated)),
      });
    }),
  );

  /** Bearer merchant key, compared against the stored hash. Seeded merchants have no key and cannot use this API. */
  async function authenticate(req: Request): Promise<Merchant> {
    const id = String(req.params['id'] ?? '');
    const header = req.header('authorization') ?? '';
    const key = header.startsWith('Bearer ') ? header.slice('Bearer '.length).trim() : '';
    const merchant = id ? await getMerchant(pool, id) : null;
    // Compare even on a miss, so timing does not reveal which ids exist.
    const expected = merchant?.merchantKeyHash ?? sha256Hex('');
    const ok = key.length > 0 && safeEqual(sha256Hex(key), expected);
    if (!merchant || !merchant.merchantKeyHash || !ok) {
      throw unauthorized('UNAUTHORIZED', 'Missing or invalid merchant key');
    }
    return merchant;
  }

  async function planView(merchant: Merchant) {
    const cap = config.merchants.freePlanMonthlyOrders;
    const plan = effectivePlan(merchant);
    const used = await countBillableSessions(pool, merchant.id, monthStart());
    return {
      plan,
      planExpiresAt: merchant.planExpiresAt ? merchant.planExpiresAt.toISOString() : null,
      usage: {
        periodStart: monthStart().toISOString(),
        paidOrders: used,
        // null = unlimited
        limit: plan === 'free' && cap > 0 ? cap : null,
      },
    };
  }

  return router;
}

function invalid(error: z.ZodError) {
  return badRequest('INVALID_REQUEST', error.issues.map((i) => `${i.path.join('.') || 'body'}: ${i.message}`).join('; '));
}
